#!/usr/bin/env python
"""SQLite → PostgreSQL 迁移工具（骨架，当前不改变运行时存储）。

功能：
1) 导出 SQLite 全部业务表到 JSON dump（含行校验和）+ 生成 PostgreSQL DDL；
2) 可选：把 dump 导入 PostgreSQL（需 psycopg + 可用 PG 实例）；
3) 可选：对账 SQLite 与 PG 的行数/校验和。

边界：这是迁移工具，不是运行时双写；应用仍用 SQLite，完成 repository 抽象后才切换。
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sqlite3
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DB = ROOT / "data" / "medagent.db"
DEFAULT_OUT = ROOT / "data" / "migration"
SKIP_TABLES = {"sqlite_sequence"}


def _canonical(row: dict) -> str:
    return json.dumps({key: row[key] for key in sorted(row)}, ensure_ascii=False, sort_keys=True)


def _checksum(rows: list[dict]) -> str:
    digest = hashlib.sha256()
    for item in sorted(_canonical(row) for row in rows):
        digest.update(item.encode("utf-8"))
        digest.update(b"\n")
    return digest.hexdigest()


def _table_columns(conn: sqlite3.Connection, table: str) -> list[str]:
    return [row[1] for row in conn.execute(f'PRAGMA table_info("{table}")').fetchall()]


def _primary_key(conn: sqlite3.Connection, table: str):
    info = conn.execute(f'PRAGMA table_info("{table}")').fetchall()
    primary = [row[1] for row in info if row[5]]
    return primary[0] if primary else None


def convert_schema(sql: str) -> str:
    """把 SQLite CREATE TABLE/INDEX 转成 PostgreSQL 近似 DDL（骨架级转换）。"""
    converted = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", "BIGSERIAL PRIMARY KEY", sql,
                       flags=re.IGNORECASE)
    converted = re.sub(r"\bAUTOINCREMENT\b", "", converted, flags=re.IGNORECASE)
    converted = re.sub(r"\bREAL\b", "DOUBLE PRECISION", converted, flags=re.IGNORECASE)
    converted = re.sub(r"\bDATETIME\b", "TIMESTAMPTZ", converted, flags=re.IGNORECASE)
    return converted.strip()


def export_database(db_path: Path) -> dict:
    if not Path(db_path).is_file():
        raise FileNotFoundError(f"SQLite 不存在：{db_path}")
    conn = sqlite3.connect(str(db_path))
    conn.row_factory = sqlite3.Row
    try:
        rows = conn.execute(
            "SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
        ).fetchall()
        tables = []
        schema_parts, index_parts = [], []
        for name, sql in rows:
            if name in SKIP_TABLES or not sql:
                continue
            schema_parts.append(convert_schema(sql) + ";")
            columns = _table_columns(conn, name)
            pk = _primary_key(conn, name)
            order = f'ORDER BY "{pk}"' if pk else ""
            data = [dict(row) for row in conn.execute(f'SELECT * FROM "{name}" {order}').fetchall()]
            tables.append({"name": name, "columns": columns, "primary_key": pk,
                           "rows": len(data), "checksum": _checksum(data), "data": data})
        for (name, sql) in conn.execute(
                "SELECT name, sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name").fetchall():
            index_parts.append(convert_schema(sql) + ";")
        return {
            "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
            "source": str(Path(db_path).resolve()),
            "tables": tables,
            "schema": schema_parts,
            "indexes": index_parts,
            "total_rows": sum(table["rows"] for table in tables),
        }
    finally:
        conn.close()


def write_artifacts(dump: dict, out_dir: Path) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    dump_path = out_dir / "dump.json"
    schema_path = out_dir / "schema.sql"
    dump_path.write_text(json.dumps(dump, ensure_ascii=False, indent=2), encoding="utf-8")
    sql = ["-- generated by production/migrate_to_pg.py", "-- review before production use", ""]
    sql.extend(dump["schema"])
    sql.append("")
    sql.extend(dump["indexes"])
    schema_path.write_text("\n".join(sql) + "\n", encoding="utf-8")
    manifest = {
        "generated_at": dump["generated_at"],
        "source": dump["source"],
        "tables": len(dump["tables"]),
        "total_rows": dump["total_rows"],
        "checksums": {table["name"]: table["checksum"] for table in dump["tables"]},
        "dump_sha256": hashlib.sha256(dump_path.read_bytes()).hexdigest(),
        "schema_sha256": hashlib.sha256(schema_path.read_bytes()).hexdigest(),
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    return manifest


def _require_psycopg():
    try:
        import psycopg  # noqa: F401
    except ImportError as exc:
        raise RuntimeError("未安装 psycopg；请 pip install 'psycopg[binary]'（或使用 production/requirements-migration.txt）") from exc
    import psycopg
    return psycopg


def import_to_pg(dump: dict, pg_url: str, recreate: bool = True) -> dict:
    """把 dump 导入 PG；recreate=True 时先删除同名表（仅迁移演练使用）。"""
    psycopg = _require_psycopg()
    from psycopg import sql as pgsql

    imported = 0
    with psycopg.connect(pg_url) as conn:
        with conn.cursor() as cur:
            if recreate:
                for table in reversed(dump["tables"]):
                    cur.execute(pgsql.SQL("DROP TABLE IF EXISTS {} CASCADE").format(pgsql.Identifier(table["name"])))
            for statement in dump["schema"]:
                cur.execute(statement)
            for statement in dump["indexes"]:
                cur.execute(statement)
            for table in dump["tables"]:
                if not table["data"]:
                    continue
                columns = table["columns"]
                query = pgsql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
                    pgsql.Identifier(table["name"]),
                    pgsql.SQL(", ").join(pgsql.Identifier(column) for column in columns),
                    pgsql.SQL(", ").join([pgsql.Placeholder()] * len(columns)),
                )
                cur.executemany(query, [tuple(row[column] for column in columns) for row in table["data"]])
                imported += len(table["data"])
                if "id" in columns:
                    cur.execute(
                        pgsql.SQL("SELECT setval(pg_get_serial_sequence({}, 'id'), COALESCE(MAX(id), 1)) FROM {}")
                        .format(pgsql.Literal(table["name"]), pgsql.Identifier(table["name"]))
                    )
        conn.commit()
    return {"imported": imported, "tables": len(dump["tables"])}


def verify_pg(dump: dict, pg_url: str) -> dict:
    """对账：SQLite dump 与 PG 的行数/内容校验和。"""
    psycopg = _require_psycopg()
    from psycopg import sql as pgsql

    mismatches = []
    with psycopg.connect(pg_url) as conn:
        with conn.cursor() as cur:
            for table in dump["tables"]:
                name = table["name"]
                order = f'ORDER BY "{table["primary_key"]}"' if table["primary_key"] else ""
                cur.execute(pgsql.SQL("SELECT COUNT(*) FROM {}").format(pgsql.Identifier(name)))
                pg_rows = cur.fetchone()[0]
                cur.execute(pgsql.SQL("SELECT * FROM {} {}").format(pgsql.Identifier(name), pgsql.SQL(order)))
                columns = [desc.name for desc in cur.description]
                data = [dict(zip(columns, row)) for row in cur.fetchall()]
                pg_checksum = _checksum(data)
                ok = pg_rows == table["rows"] and pg_checksum == table["checksum"]
                if not ok:
                    mismatches.append({"table": name, "sqlite_rows": table["rows"], "pg_rows": pg_rows,
                                       "sqlite_checksum": table["checksum"], "pg_checksum": pg_checksum})
    return {"ok": not mismatches, "checked": len(dump["tables"]), "mismatches": mismatches}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="SQLite → PostgreSQL 迁移骨架")
    parser.add_argument("--db", default=str(DEFAULT_DB))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--pg-url", default="")
    parser.add_argument("--import", dest="do_import", action="store_true", help="导入 PostgreSQL（会先重建表）")
    parser.add_argument("--verify", action="store_true", help="对账 SQLite 与 PostgreSQL")
    args = parser.parse_args(argv)

    dump = export_database(Path(args.db))
    manifest = write_artifacts(dump, Path(args.out))
    print(f"导出完成：{manifest['tables']} 张表，{manifest['total_rows']} 行 → {args.out}")
    print(f"dump SHA256：{manifest['dump_sha256']}")

    if args.do_import:
        if not args.pg_url:
            print("缺少 --pg-url", file=sys.stderr)
            return 2
        result = import_to_pg(dump, args.pg_url, recreate=True)
        print(f"导入完成：{result['imported']} 行 / {result['tables']} 表")
    if args.verify:
        if not args.pg_url:
            print("缺少 --pg-url", file=sys.stderr)
            return 2
        result = verify_pg(dump, args.pg_url)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        if not result["ok"]:
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
